import { createHash } from 'node:crypto'
import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const profileDir = path.join(root, 'public', 'profile')
const generatedDir = path.join(profileDir, 'generated')
const manifestPath = path.join(
  root,
  'content',
  'profile-portrait.generated.ts'
)

const entries = await readdir(profileDir, { withFileTypes: true })
const portraits = entries
  .filter(
    (entry) =>
      entry.isFile() &&
      /\.(?:jpe?g|png)$/i.test(entry.name)
  )
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b))

if (portraits.length === 0) {
  throw new Error(
    'No profile portrait found. Add one JPG, JPEG, or PNG file to public/profile.'
  )
}

if (portraits.length > 1) {
  throw new Error(
    `Multiple profile portraits found: ${portraits.join(', ')}. Keep exactly one JPG, JPEG, or PNG file in public/profile.`
  )
}

const sourceName = portraits[0]
const sourcePath = path.join(profileDir, sourceName)
const source = await readFile(sourcePath)
const extension = path.extname(sourceName).toLowerCase()
const blobHash = createHash('sha1')
  .update(`blob ${source.length}\0`)
  .update(source)
  .digest('hex')
  .slice(0, 12)

await rm(generatedDir, { recursive: true, force: true })
await mkdir(generatedDir, { recursive: true })

const generatedName = `portrait-${blobHash}${extension}`
await copyFile(
  sourcePath,
  path.join(generatedDir, generatedName)
)

const manifest = `// Generated by scripts/sync-profile-portrait.mjs.
// Keep exactly one JPG, JPEG, or PNG source image in public/profile.

export const profilePortrait = {
  src: '/profile/generated/${generatedName}',
} as const
`

await writeFile(manifestPath, manifest, 'utf8')

console.log(
  `Profile portrait: ${sourceName} -> ${generatedName}`
)
